/**
 * Captures the Prisma schema as plain SQLite DDL.
 *
 * The packaged Electron app cannot run `prisma migrate`, so this snapshot is
 * applied directly on first launch from `electron/main/prisma.ts`.
 *
 * Run after every schema change:  npm run prisma:snapshot
 */
import { execSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const sql = execSync(
  'npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script',
  { cwd: root, encoding: 'utf-8' }
).trim()

if (!sql.includes('CREATE TABLE')) {
  throw new Error('Prisma did not produce any DDL — aborting snapshot')
}

// Re-runs must stay harmless: the schema is reapplied on every launch.
const idempotent = sql
  .replace(/CREATE TABLE "/g, 'CREATE TABLE IF NOT EXISTS "')
  .replace(/CREATE UNIQUE INDEX "/g, 'CREATE UNIQUE INDEX IF NOT EXISTS "')
  .replace(/CREATE INDEX "/g, 'CREATE INDEX IF NOT EXISTS "')

mkdirSync(resolve(root, 'prisma/migrations/0000_init'), { recursive: true })
writeFileSync(resolve(root, 'prisma/migrations/0000_init/migration.sql'), idempotent + '\n', 'utf-8')
writeFileSync(
  resolve(root, 'electron/main/db-snapshot.ts'),
  '// AUTO-GENERATED by scripts/prisma-snapshot.mjs — do not edit by hand.\n' +
    '// SQLite DDL snapshot applied to the user-data database on first launch.\n\n' +
    `export const SNAPSHOT_SQL = ${JSON.stringify(idempotent)}\n`,
  'utf-8'
)

console.log(`Snapshot written (${idempotent.split(';').filter(Boolean).length} statements)`)
