/**
 * Employee work-file storage (PDF/Excel attachments).
 *
 * Files live in a single, predictable folder the user can open from the UI:
 *   <Documents>/HR-System/EmployeeFiles
 * The database stores only a unique file name + metadata, so the folder can be
 * browsed/backed up independently of the app database.
 *
 * Stored files are named `<code>_<employee name>.<ext>` (e.g.
 * `2689_أحمد عبد القادر.pdf`) so the folder stays self-describing.
 */
import { shell } from 'electron'
import fs from 'fs'
import path from 'path'
import { PrismaClient } from '@prisma/client'
import { ApiError } from '../../shared/types'
import type { EmployeeFilePreview } from '../../shared/types'
import { assertFileSignature } from './file-guard'
import { DOCUMENT_FOLDERS, getDocumentFolderDir } from './document-folders'
import { MAX_UPLOAD_SIZE, MAX_UPLOAD_SIZE_MB } from '../../shared/upload-limits'

const ALLOWED_EXTENSIONS = new Set(['.pdf', '.xlsx', '.xls', '.xlsm', '.csv'])
const PREVIEW_MAX_ROWS = 2000
const PREVIEW_MAX_COLS = 60

export function getEmployeeFilesDir(): string {
  return getDocumentFolderDir(DOCUMENT_FOLDERS.employeeFiles)
}

function ensureDir(): string {
  const dir = getEmployeeFilesDir()
  fs.mkdirSync(dir, { recursive: true })
  return dir
}

/** Makes a value safe as a single file-name segment (no path separators). */
function sanitizeSegment(value: string): string {
  return value
    .replace(/[\\/:*?"<>|]+/g, '_')
    .replace(/\s+/g, ' ')
    .replace(/^[.\s]+|[.\s]+$/g, '')
    .slice(0, 80)
}

/**
 * Employee files are named after the employee so the folder is easy to browse:
 * `<code>_<name><ext>` (e.g. `2689_أحمد عبد القادر.pdf`). The employee code is
 * unique, so the stored name is unique per employee.
 */
export function buildStoredName(code: string | number, name: string, ext: string): string {
  const codePart = sanitizeSegment(String(code)) || 'employee'
  const namePart = sanitizeSegment(name) || 'employee'
  return `${codePart}_${namePart}`.slice(0, 150) + ext
}

function assertAllowedExtension(originalName: string): string {
  const ext = path.extname(originalName).toLowerCase()
  if (!ALLOWED_EXTENSIONS.has(ext)) {
    throw new ApiError('VALIDATION', 'Only PDF and Excel (xlsx/xls/csv) files are allowed')
  }
  return ext
}

function resolveStoredPath(storedName: string): string {
  // storedName is generated by this module, but never trust DB contents in a path.
  const safe = path.basename(storedName)
  if (!safe || safe !== storedName) {
    throw new ApiError('VALIDATION', 'Invalid file name')
  }
  return path.join(getEmployeeFilesDir(), safe)
}

function deleteQuietly(filePath: string): void {
  try {
    fs.rmSync(filePath, { force: true })
  } catch {
    // best effort — a missing/locked file must not break the unlink
  }
}

/** Removes a stored employee file by its stored name (no-op when null/missing). */
export function deleteStoredEmployeeFile(storedName: string | null | undefined): void {
  if (!storedName) return
  deleteQuietly(resolveStoredPath(storedName))
}

export interface EmployeeWithFile {
  id: string
  code: string
  fileStoredName: string | null
  fileOriginalName: string | null
}

/** Writes the upload into the files folder and links it to the employee. */
export async function attachEmployeeFile(
  prisma: PrismaClient,
  employeeId: string,
  data: Buffer,
  originalName: string
): Promise<void> {
  const ext = assertAllowedExtension(originalName)
  if (data.byteLength === 0) throw new ApiError('VALIDATION', 'The file is empty')
  if (data.byteLength > MAX_UPLOAD_SIZE) {
    throw new ApiError('VALIDATION', `File exceeds the ${MAX_UPLOAD_SIZE_MB} MB limit`)
  }
  assertFileSignature(originalName, data)

  const employee = await prisma.employee.findUnique({ where: { id: employeeId } })
  if (!employee) throw new ApiError('NOT_FOUND', 'Employee not found')

  const dir = ensureDir()
  const storedName = buildStoredName(employee.code, employee.name, ext)
  const target = path.join(dir, storedName)
  fs.writeFileSync(target, data)

  // Replace: drop the previous physical file only when the name changed, so we
  // never delete the file we just wrote (the stored name is now deterministic).
  if (employee.fileStoredName && employee.fileStoredName !== storedName) {
    deleteQuietly(resolveStoredPath(employee.fileStoredName))
  }

  await prisma.employee.update({
    where: { id: employeeId },
    data: {
      fileStoredName: storedName,
      fileOriginalName: storedName,
      fileSize: data.byteLength,
      fileLinkedAt: new Date()
    }
  })
}

/** Unlinks the employee's file and removes it from disk. */
export async function removeEmployeeFile(
  prisma: PrismaClient,
  employeeId: string
): Promise<void> {
  const employee = await prisma.employee.findUnique({ where: { id: employeeId } })
  if (!employee) throw new ApiError('NOT_FOUND', 'Employee not found')
  if (!employee.fileStoredName) throw new ApiError('NOT_FOUND', 'No file is linked')

  deleteQuietly(resolveStoredPath(employee.fileStoredName))

  await prisma.employee.update({
    where: { id: employeeId },
    data: {
      fileStoredName: null,
      fileOriginalName: null,
      fileSize: null,
      fileLinkedAt: null
    }
  })
}

/** Reads the linked file and builds a preview payload (PDF bytes or a grid). */
export async function previewEmployeeFile(
  prisma: PrismaClient,
  employeeId: string
): Promise<EmployeeFilePreview> {
  const employee = await prisma.employee.findUnique({ where: { id: employeeId } })
  if (!employee) throw new ApiError('NOT_FOUND', 'Employee not found')
  if (!employee.fileStoredName) throw new ApiError('NOT_FOUND', 'No file is linked')

  const filePath = resolveStoredPath(employee.fileStoredName)
  if (!fs.existsSync(filePath)) {
    throw new ApiError('NOT_FOUND', 'The file is missing on disk')
  }

  const ext = path.extname(filePath).toLowerCase()
  const size = fs.statSync(filePath).size
  const base = {
    originalName: employee.fileOriginalName,
    ext,
    size
  }

  if (ext === '.pdf') {
    const data = fs.readFileSync(filePath)
    return { kind: 'pdf', ...base, data: new Uint8Array(data) }
  }

  const XLSX = await import('xlsx')
  const workbook = XLSX.read(fs.readFileSync(filePath), { type: 'buffer' })
  const sheetName = workbook.SheetNames[0] ?? null
  const sheet = sheetName ? workbook.Sheets[sheetName] : undefined
  if (!sheet) throw new ApiError('VALIDATION', 'The spreadsheet has no sheets')

  const grid = XLSX.utils.sheet_to_json<string[]>(sheet, {
    header: 1,
    raw: false,
    defval: '',
    blankrows: false
  })
  const totalRows = grid.length
  const rows = grid
    .slice(0, PREVIEW_MAX_ROWS)
    .map((row) => row.slice(0, PREVIEW_MAX_COLS).map((cell) => String(cell ?? '')))

  return {
    kind: 'table',
    ...base,
    sheetName,
    rows,
    totalRows,
    truncated: totalRows > PREVIEW_MAX_ROWS
  }
}

/** Creates the folder if needed and reveals it in the OS file browser. */
export async function revealEmployeeFilesDir(): Promise<void> {
  const dir = ensureDir()
  await shell.openPath(dir)
}
